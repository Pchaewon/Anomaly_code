    def _config(self) -> Config:
        f = lambda key: float(self.fields[key].get().strip())
        start_text = self.fields["start_bow"].get().strip()
        return Config(
            target=f("target"), lower=f("lower"), upper=f("upper"),
            step=f("step"), max_change=f("max_change"), max_total=f("max_total"),
            delay=1 if self.fields["delay"].get() == "N+1" else 2,
            run_count=int(self.fields["runs"].get()),
            process_schedule=self.fields["schedule"].get(),
            start_bow=None if not start_text else float(start_text),
            true_slope_13=f("true_slope_13"), true_slope_18=f("true_slope_18"),
            offset_18=f("offset_18"), noise_std=f("noise"), drift=f("drift"),
            seed=int(self.fields["seed"].get()), ridge_alpha=f("alpha"),
            auto=self.fields["mode"].get() == "자동 추천",
        )

    def load_csv(self):
        path = filedialog.askopenfilename(filetypes=[("CSV 파일", "*.csv"), ("모든 파일", "*.*")])
        if not path:
            return
        try:
            self.df = load_process_csv(path)
        except Exception as e:
            messagebox.showerror("CSV 불러오기 오류", str(e))
            return
        self.source_name = f"실제 CSV: {Path(path).name} ({len(self.df)}행)"
        self.fields["start_bow"].set("")  # actual last Bow, not hardcoded starting value
        self.fields["schedule"].set(SCHEDULE_OPTIONS[0])
        self.reset_simulator()

    def use_demo(self):
        self.df = make_demo_data()
        self.source_name = "내장 데모 데이터 (가상 데이터)"
        self.fields["start_bow"].set("1.8")
        self.fields["schedule"].set(SCHEDULE_OPTIONS[0])
        self.reset_simulator()

    def reset_simulator(self):
        try:
            self.sim = Simulator(self.df, self._config())
        except Exception as e:
            messagebox.showerror("설정 오류", str(e))
            return
        s = self.sim
        n13 = (self.df["process_hours"] == 13.3).sum()
        n18 = (self.df["process_hours"] == 18.5).sum()
        m13 = s.source_by_time[13.3]
        m18 = s.source_by_time[18.5]
        self.source_label.configure(text=(
            f"{self.source_name}\n13.3Hr: {n13}행 [{m13}] / 18.5Hr: {n18}행 [{m18}]\n"
            f"마지막 CSV Bow: {float(self.df.iloc[-1][Y_COL]):.3f} / "
            f"Simulation Start: {s.y0:.3f}\n"
            f"[mode] 해당 시간별 Ridge / [pooled] 데이터 부족으로 전체 Ridge 사용"
        ))
        self.refresh()
        self.status_var.set("설정 완료: Spec 1.0~1.5, Target 1.25. 다음 Run 1회 또는 전체 실행 선택")

    def step_once(self):
        if self.sim is None:
            return
        row = self.sim.next_run()
        if row is None:
            messagebox.showinfo("완료", "설정한 Run 수만큼 시뮬레이션을 완료했습니다.")
            return
        self.refresh()
        wait = f" / Run {self.sim.pending['apply_run']} 예약" if self.sim.pending else ""
        self.status_var.set(f"Run {row['run']} ({row['process_time']}) | Bow {row['bow_tuned']:.3f} | "
                            f"{row['decision']}: {row['reason']}{wait}")

    def run_all(self):
        if self.sim is None:
            return
        self.sim.run_all()
        self.refresh()
        self.status_var.set(f"완료 {self.sim.next_idx}Run | {self.sim.metrics()}")

    def manual_preset(self, value: float):
        for var in self.manual_entries:
            var.set(f"{value:+.2f}")

    def schedule_manual(self):
        if self.sim is None:
            return
        if self.sim.cfg.auto:
            messagebox.showinfo("모드 확인", "'제어 방식'을 수동 조정으로 바꾼 뒤 초기화해 주세요.")
            return
        try:
            change = np.array([float(var.get()) for var in self.manual_entries], dtype=float)
            ok = self.sim.schedule(self.sim.x_active + change, "MANUAL")
            if not ok:
                messagebox.showinfo("변경 없음", "온도 변경량이 0이거나 누적 변경 한도를 초과했습니다.")
                return
        except Exception as e:
            messagebox.showerror("수동 예약 오류", str(e))
            return
        self.refresh()
        self.status_var.set(f"수동 레시피를 Run {self.sim.pending['apply_run']}에 예약했습니다.")

    def refresh(self):
        s = self.sim
        if s is None:
            return
        df = s.history_frame()
        cfg = s.cfg
        self.ax_bow.clear()
        self.ax_temp.clear()
        self.ax_bow.axhspan(cfg.lower, cfg.upper, color="#3ca370", alpha=0.14,
                            label=f"Spec {cfg.lower:g}~{cfg.upper:g}")
        self.ax_bow.axhline(cfg.target, color="black", ls="--", lw=1, label=f"Target {cfg.target:g}")
        if not df.empty:
            self.ax_bow.plot(df["run"], df["bow_keep"], color="#999999", lw=1.4, label="Keep")
            self.ax_bow.plot(df["run"], df["bow_tuned"], color="#1767ad", lw=2, label="RM / Manual")
            applied = df[df["applied"]]
            if not applied.empty:
                self.ax_bow.scatter(applied["run"], applied["bow_tuned"], color="#ed8b31",
                                    marker="D", s=24, label="Recipe applied", zorder=3)
        self.ax_bow.set_title("Bow vs Run (simulated delayed control)")
        self.ax_bow.set_ylabel("Avg Bow BF Total")
        self.ax_bow.set_xlabel("Run")
        self.ax_bow.grid(alpha=0.24)
        self.ax_bow.legend(fontsize=8, loc="best")

        self.ax_temp.plot(PCTS, s.x0, color="#999999", ls="--", label="Initial")
        self.ax_temp.plot(PCTS, s.x_active, color="#1767ad", marker="o", label="Current")
        if s.pending:
            self.ax_temp.plot(PCTS, s.pending["recipe"], color="#ed8b31", marker="s",
                              label=f"Planned Run {s.pending['apply_run']}")
        self.ax_temp.set_xlabel("Profile (%)")
        self.ax_temp.set_ylabel("Temperature (C)")
        self.ax_temp.grid(alpha=0.24)
        self.ax_temp.legend(fontsize=8, loc="best")
        self.canvas.draw_idle()
        self.metric_label.configure(text=s.metrics())

        for item in self.recipe_table.get_children():
            self.recipe_table.delete(item)
        planned = s.pending["recipe"] if s.pending else s.x_active
        mode = s.pending["process_hours"] if s.pending else float(s.run_hours[min(s.next_idx, cfg.run_count - 1)])
        for p, active, future, sen in zip(PCTS, s.x_active, planned, s.sensitivity_by_time[mode]):
            self.recipe_table.insert("", "end", values=(
                f"{p}%", f"{active:.3f}", f"{future:.3f}", f"{future-active:+.3f}", f"{sen:+.5f}"
            ))
        for item in self.hist_table.get_children():
            self.hist_table.delete(item)
        if not df.empty:
            for _, row in df.tail(500).iloc[::-1].iterrows():
                next_id = "-" if pd.isna(row["apply_to"]) else str(int(row["apply_to"]))
                self.hist_table.insert("", "end", values=(
                    int(row["run"]), row["process_time"], f"{row['cumulative_hours']:.1f}",
                    f"{row['bow_tuned']:.3f}", f"{row['bow_keep']:.3f}", row["decision"],
                    "Y" if row["applied"] else "-", next_id, row["reason"]
                ), tags=(row["decision"],))

    def export(self):
        if not self.sim or not self.sim.history:
            messagebox.showinfo("저장 불가", "먼저 Run을 실행해 주세요.")
            return
        folder = filedialog.askdirectory(title="저장할 폴더 선택")
        if not folder:
            return
        root = Path(folder)
        try:
            self.sim.history_frame().to_csv(root / "simulation_history.csv", index=False, encoding="utf-8-sig")
            s = self.sim
            planned = s.pending["recipe"] if s.pending else s.x_active
            mode = s.pending["process_hours"] if s.pending else float(s.run_hours[min(s.next_idx, s.cfg.run_count-1)])
            pd.DataFrame({
                "profile": X_COLS, "Current_Temp": s.x_active, "Planned_Temp": planned,
                "Change_Temp": planned - s.x_active,
                "Ridge_Sensitivity": s.sensitivity_by_time[mode],
                "Weights": s.weights_by_time[mode],
                "Process_Time": f"{mode:g}Hr",
            }).to_csv(root / "simulation_recipe.csv", index=False, encoding="utf-8-sig")
            self.figure.savefig(root / "simulation_plot.png", dpi=150)
        except Exception as e:
            messagebox.showerror("저장 오류", str(e))
            return
        messagebox.showinfo("저장 완료", f"{root}\n시뮬레이션 CSV 2개 및 그래프 PNG 1개 저장")


