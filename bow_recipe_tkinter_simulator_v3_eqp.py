    def schedule_manual(self):
        if self.sim is None:
            return
        if self.sim.cfg.auto:
            messagebox.showinfo("모드 확인", "'제어 방식'을 수동 조정으로 바꾼 뒤 초기화해 주세요.")
            return
        try:
            change = np.array([float(var.get()) for var in self.manual_entries], dtype=float)
            ok = self.sim.schedule(self.sim.x_active + change, "MANUAL")
            if not ok:
                messagebox.showinfo("변경 없음", "온도 변경량이 0이거나 누적 변경 한도를 초과했습니다.")
                return
        except Exception as e:
            messagebox.showerror("수동 예약 오류", str(e))
            return
        self.refresh()
        self.status_var.set(f"수동 레시피를 Run {self.sim.pending['apply_run']}에 예약했습니다.")

    def refresh(self):
        s = self.sim
        if s is None:
            return
        df = s.history_frame()
        cfg = s.cfg
        machine = self._equipment_data(s.eqp_id)
        n13 = int((machine["process_hours"] == 13.3).sum())
        n18 = int((machine["process_hours"] == 18.5).sum())
        self._render_latest()
        self.source_label.configure(text=(
            f"{self.source_name}\n"
            f"선택 장비: {s.eqp_id} / 장비 이력: {len(machine)}행\n"
            f"13.3Hr: {n13}행 [{s.source_by_time[13.3]}] / "
            f"18.5Hr: {n18}행 [{s.source_by_time[18.5]}]\n"
            f"최근 실측 Bow {float(machine.iloc[-1][Y_COL]):.3f} / "
            f"시뮬레이션 시작 Bow {s.y0:.3f}\n"
            f"[mode] 해당 장비+시간 / [pooled] 해당 장비 전체만 학습"
        ))
        self.ax_bow.clear()
        self.ax_temp.clear()
        self.ax_bow.axhspan(cfg.lower, cfg.upper, color="#3ca370", alpha=0.14,
                            label=f"Spec {cfg.lower:g}~{cfg.upper:g}")
        self.ax_bow.axhline(cfg.target, color="black", ls="--", lw=1, label=f"Target {cfg.target:g}")
        if not df.empty:
            self.ax_bow.plot(df["run"], df["bow_keep"], color="#999999", lw=1.4, label="Keep")
            self.ax_bow.plot(df["run"], df["bow_tuned"], color="#1767ad", lw=2, label="RM / Manual")
            applied = df[df["applied"]]
            if not applied.empty:
                self.ax_bow.scatter(applied["run"], applied["bow_tuned"], color="#ed8b31",
                                    marker="D", s=24, label="Recipe applied", zorder=3)
        self.ax_bow.set_title(f"{s.eqp_id} | Bow vs Run (simulated delayed control)")
        self.ax_bow.set_ylabel("Avg Bow BF Total")
        self.ax_bow.set_xlabel("Run")
        self.ax_bow.grid(alpha=0.24)
        self.ax_bow.legend(fontsize=8, loc="best")

        self.ax_temp.plot(PCTS, s.x0, color="#999999", ls="--", label="Initial")
        self.ax_temp.plot(PCTS, s.x_active, color="#1767ad", marker="o", label="Current")
        if s.pending:
            self.ax_temp.plot(PCTS, s.pending["recipe"], color="#ed8b31", marker="s",
                              label=f"Planned Run {s.pending['apply_run']}")
        self.ax_temp.set_xlabel("Profile (%)")
        self.ax_temp.set_ylabel("Temperature (C)")
        self.ax_temp.grid(alpha=0.24)
        self.ax_temp.legend(fontsize=8, loc="best")
        self.canvas.draw_idle()
        self.metric_label.configure(text=s.metrics())

        for item in self.recipe_table.get_children():
            self.recipe_table.delete(item)
        planned = s.pending["recipe"] if s.pending else s.x_active
        mode = s.pending["process_hours"] if s.pending else float(s.run_hours[min(s.next_idx, cfg.run_count - 1)])
        for p, active, future, sen in zip(PCTS, s.x_active, planned, s.sensitivity_by_time[mode]):
            self.recipe_table.insert("", "end", values=(
                f"{p}%", f"{active:.3f}", f"{future:.3f}", f"{future-active:+.3f}", f"{sen:+.5f}"
            ))
        for item in self.hist_table.get_children():
            self.hist_table.delete(item)
        if not df.empty:
            for _, row in df.tail(500).iloc[::-1].iterrows():
                next_id = "-" if pd.isna(row["apply_to"]) else str(int(row["apply_to"]))
                self.hist_table.insert("", "end", values=(
                    int(row["run"]), row["process_time"], f"{row['cumulative_hours']:.1f}",
                    f"{row['bow_tuned']:.3f}", f"{row['bow_keep']:.3f}", row["decision"],
                    "Y" if row["applied"] else "-", next_id, row["reason"]
                ), tags=(row["decision"],))

    def export(self):
        if not self.sim or not self.sim.history:
            messagebox.showinfo("저장 불가", "먼저 Run을 실행해 주세요.")
            return
        folder = filedialog.askdirectory(title="저장할 폴더 선택")
        if not folder:
            return
        root = Path(folder)
        safe_eqp = re.sub(r"[^\w.-]+", "_", self.sim.eqp_id)
        try:
            self.sim.history_frame().assign(EQP_ID=self.sim.eqp_id).to_csv(
                root / f"simulation_history_{safe_eqp}.csv", index=False, encoding="utf-8-sig")
            s = self.sim
            planned = s.pending["recipe"] if s.pending else s.x_active
            mode = s.pending["process_hours"] if s.pending else float(s.run_hours[min(s.next_idx, s.cfg.run_count-1)])
            pd.DataFrame({
                "profile": X_COLS, "Current_Temp": s.x_active, "Planned_Temp": planned,
                "Change_Temp": planned - s.x_active,
                "Ridge_Sensitivity": s.sensitivity_by_time[mode],
                "Weights": s.weights_by_time[mode],
                "Process_Time": f"{mode:g}Hr",
            }).assign(EQP_ID=self.sim.eqp_id).to_csv(
                root / f"simulation_recipe_{safe_eqp}.csv", index=False, encoding="utf-8-sig")
            self.figure.savefig(root / f"simulation_plot_{safe_eqp}.png", dpi=150)
        except Exception as e:
            messagebox.showerror("저장 오류", str(e))
            return
        messagebox.showinfo("저장 완료", f"{root}\nEQP {self.sim.eqp_id} 시뮬레이션 CSV 2개 및 그래프 PNG 1개 저장")


