X_COLS = [f"frame in temp {i}pct" for i in range(0, 101, 10)]
Y_COL = "avg bow bf total"
PROCESS_COL = "process_time"
EQP_COL = "EQP_ID"
PCTS = list(range(0, 101, 10))
TIME_MODES = (13.3, 18.5)
SCHEDULE_OPTIONS = ("CSV 최근 30행 반복", "13.3Hr 고정", "18.5Hr 고정")


def parse_process_time(value) -> float:
    """Convert 13.3Hr / 18.5Hr, 13.3 / 18.5 (including whitespace) to hours."""
    match = re.fullmatch(r"\s*(\d+(?:\.\d+)?)\s*(?:h|hr|hrs)?\s*", str(value), flags=re.I)
    if not match:
        raise ValueError(f"지원하지 않는 process_time 값: {value!r} (예: 13.3Hr, 18.5Hr)")
    val = float(match.group(1))
    for allowed in TIME_MODES:
        if np.isclose(val, allowed, atol=1e-6, rtol=0):
            return allowed
    raise ValueError(f"process_time={value!r}: 13.3Hr 또는 18.5Hr만 지원합니다.")


def make_demo_data(seed: int = 8) -> pd.DataFrame:
    """Synthetic multiple-EQP data, with realistic within-EQP differences."""
    rng = np.random.default_rng(seed)
    frames = []
    for eqp, base_shift, bow_shift in [
        ("EQP_A01", 0.0, 0.0),
        ("EQP_A02", 5.0, 0.40),
        ("EQP_B01", -3.0, -0.35),
    ]:
        n = 160
        base = np.linspace(350, 450, len(X_COLS)) + base_shift
        x = base + rng.normal(0, 1.6, (n, 1)) + rng.normal(0, 0.65, (n, 11))
        times = rng.choice(TIME_MODES, size=n, p=[0.55, 0.45])
        y = 1.7 + bow_shift - 0.06 * np.sum(x - base, axis=1) + 0.12 * (times == 18.5)
        y += rng.normal(0, 0.12, n)
        part = pd.DataFrame(x, columns=X_COLS)
        part[EQP_COL] = eqp
        part[Y_COL] = y
        part[PROCESS_COL] = np.where(times == 13.3, "13.3Hr", "18.5Hr")
        part["process_hours"] = times
        frames.append(part)
    return pd.concat(frames, ignore_index=True)


def load_process_csv(path: str) -> pd.DataFrame:
    data = pd.read_csv(path, encoding="utf-8-sig")
    data.columns = [str(c).strip() for c in data.columns]
    required = [EQP_COL] + X_COLS + [Y_COL, PROCESS_COL]
    missing = [c for c in required if c not in data.columns]
    if missing:
        raise ValueError("CSV에 필요한 컬럼이 없습니다:\n" + ", ".join(missing))
    data = data.copy()
    data[EQP_COL] = data[EQP_COL].astype("string").str.strip()
    data[EQP_COL] = data[EQP_COL].replace("", pd.NA)
    for c in X_COLS + [Y_COL]:
        data[c] = pd.to_numeric(data[c], errors="coerce")
    data = data.dropna(subset=required).reset_index(drop=True)
    if data.empty:
        raise ValueError("유효한 온도/Bow/process_time/EQP_ID 행이 없습니다.")
    data["process_hours"] = data[PROCESS_COL].apply(parse_process_time)
    # Keep input row order; group filtering preserves chronological order for each EQP.
    # Do not ever mix different EQP_ID into one Ridge training set.
    if data.groupby(EQP_COL).size().max() < 5:
        raise ValueError("모든 장비가 5행 미만입니다. 장비별 유효 데이터 최소 5행이 필요합니다.")
    return data


def ridge_sensitivity(frame: pd.DataFrame, alpha: float) -> np.ndarray:
    x = frame[X_COLS].to_numpy(float)
    y = frame[Y_COL].to_numpy(float)
    scaler = StandardScaler()
    z = scaler.fit_transform(x)
    model = Ridge(alpha=alpha)
    model.fit(z, y)
    # dBow/dTemp in original engineering units.
    return model.coef_ / scaler.scale_


@dataclass(frozen=True)
class Config:
    target: float = 1.25
    lower: float = 1.0
    upper: float = 1.5
    step: float = 0.5
    max_change: float = 2.0
    max_total: float = 5.0
    delay: int = 2
    run_count: int = 150
    process_schedule: str = SCHEDULE_OPTIONS[0]
    start_bow: float | None = None
    true_slope_13: float = -0.06
    true_slope_18: float = -0.06
    offset_18: float = 0.0
    noise_std: float = 0.05
    drift: float = 0.0
    seed: int = 42
    ridge_alpha: float = 10.0
    auto: bool = True

    def validate(self) -> None:
        if not self.lower <= self.target <= self.upper or self.lower >= self.upper:
            raise ValueError("Lower < Upper, Lower ≤ Target ≤ Upper 관계를 만족해야 합니다.")
        if not 0 < self.step or not 0 < self.max_change or not 0 < self.max_total:
            raise ValueError("Step Size 및 온도 변경 한도는 양수여야 합니다.")
        if self.delay not in (1, 2) or not 1 <= self.run_count <= 5000:
            raise ValueError("적용 시점은 N+1 또는 N+2, Run 수는 1~5000이어야 합니다.")
        if self.process_schedule not in SCHEDULE_OPTIONS:
            raise ValueError("지원하지 않는 가공시간 스케줄입니다.")
        if self.noise_std < 0 or self.ridge_alpha < 0:
            raise ValueError("Noise 및 Ridge alpha는 0 이상이어야 합니다.")
        if self.true_slope_13 > 0 or self.true_slope_18 > 0:
            raise ValueError("온도 상승 시 Bow 감소 가정이므로 가상 민감도는 0 이하이어야 합니다.")


class Simulator:
    """Headless testable simulation engine, independent of Tkinter."""

    def __init__(self, data: pd.DataFrame, cfg: Config):
        cfg.validate()
        if len(data) < 5:
            raise ValueError(f"해당 장비의 유효 데이터는 {len(data)}행입니다. 최소 5행이 필요합니다.")
        if EQP_COL not in data or data[EQP_COL].nunique() != 1:
            raise ValueError("Simulator에는 정확히 한 장비(EQP_ID)의 데이터만 전달해야 합니다.")
        self.eqp_id = str(data.iloc[-1][EQP_COL])
        self.cfg = cfg
        self.data = data.copy()
        if "process_hours" not in self.data:
            self.data["process_hours"] = self.data[PROCESS_COL].apply(parse_process_time)
        self.x0 = self.data.iloc[-1][X_COLS].to_numpy(float)
        self.y0 = float(self.data.iloc[-1][Y_COL]) if cfg.start_bow is None else cfg.start_bow

        train = self.data.iloc[:-1]
        pooled = ridge_sensitivity(train, cfg.ridge_alpha)
        self.sensitivity_by_time = {}
        self.source_by_time = {}
        self.direction_by_time = {}
        self.weights_by_time = {}
        self.fallback_by_time = {}
        self.train_count_by_time = {}
        for hours in TIME_MODES:
            subset = train[train["process_hours"] == hours]
            count = len(subset)
            # For a stable mode-specific slope, need enough rows in that mode.
            sens = ridge_sensitivity(subset, cfg.ridge_alpha) if count >= 20 else pooled.copy()
            self.sensitivity_by_time[hours] = sens
            self.source_by_time[hours] = "mode" if count >= 20 else "pooled"
            self.train_count_by_time[hours] = count
            neg = np.maximum(-sens, 0)
            fallback = float(neg.sum()) < 1e-8
            if fallback:
                neg = np.ones(11)
            weights = neg / neg.sum()
            self.weights_by_time[hours] = weights
            self.direction_by_time[hours] = -weights
            self.fallback_by_time[hours] = fallback

        self.run_hours = self._build_run_hours()
        self.x_active = self.x0.copy()
        self.pending = None
        self.applied_count = 0
        self.reserved_count = 0
        self.history: list[dict] = []
        self.next_idx = 0
        rng = np.random.default_rng(cfg.seed)
        self.noise = rng.normal(0, cfg.noise_std, cfg.run_count)
        self.noise[0] = 0.0
        self.cumulative_hours = 0.0

    def _build_run_hours(self) -> np.ndarray:
        if self.cfg.process_schedule == SCHEDULE_OPTIONS[1]:
            return np.full(self.cfg.run_count, 13.3)
        if self.cfg.process_schedule == SCHEDULE_OPTIONS[2]:
            return np.full(self.cfg.run_count, 18.5)
        recent = self.data["process_hours"].tail(30).to_numpy(float)
        schedule = np.resize(recent, self.cfg.run_count)
        # Run 0 reflects the process time of the latest actual measurement.
        schedule[0] = float(self.data.iloc[-1]["process_hours"])
        return schedule

    def _slope(self, hours: float) -> float:
        return self.cfg.true_slope_13 if hours == 13.3 else self.cfg.true_slope_18

    def _mode_offset(self, hours: float) -> float:
        base_mode = self.run_hours[0]
        return self.cfg.offset_18 * (int(hours == 18.5) - int(base_mode == 18.5))

    def propose(self, bow: float, application_run: int) -> np.ndarray:
        hours = float(self.run_hours[application_run])
        direction = self.direction_by_time[hours]
        error = bow - self.cfg.target
        step = self.cfg.step / ((self.applied_count + 1) ** 0.6)
        change = -step * error * direction
        change = np.clip(change, -self.cfg.max_change, self.cfg.max_change)
        return np.clip(self.x_active + change,
                       self.x0 - self.cfg.max_total, self.x0 + self.cfg.max_total)

    def latest_recommendation(self) -> dict:
        """One-step recommendation from the latest *measured* row, without running a simulation."""
        bow = float(self.data.iloc[-1][Y_COL])
        x = self.x0.copy()
        # Future processing time is unknown; use chosen simulation schedule as assumption.
        apply_run = min(self.cfg.delay, self.cfg.run_count - 1)
        hours = float(self.run_hours[apply_run])
        sensitivity = self.sensitivity_by_time[hours]
        error = bow - self.cfg.target
        if self.cfg.lower <= bow <= self.cfg.upper:
            decision = "KEEP"
            recommended = x.copy()
            reason = "실측 Bow가 Spec 내에 있어 레시피 유지"
        else:
            direction = self.direction_by_time[hours]
            change = -self.cfg.step * error * direction
            change = np.clip(change, -self.cfg.max_change, self.cfg.max_change)
            recommended = np.clip(x + change,
                                  self.x0 - self.cfg.max_total, self.x0 + self.cfg.max_total)
            decision = "TUNE" if not np.allclose(recommended, x, atol=1e-10, rtol=0) else "LIMIT"
            reason = "실측 Bow가 Spec을 벗어나 레시피 변경 제안" if decision == "TUNE" else "온도 변경 한도로 변경 불가"
        return {
            "eqp_id": self.eqp_id,
            "n_rows": len(self.data),
            "bow": bow,
            "target": self.cfg.target,
            "latest_hours": float(self.data.iloc[-1]["process_hours"]),
            "suggested_hours": hours,
            "decision": decision,
            "reason": reason,
            "current": x,
            "recommended": recommended,
            "change": recommended-x,
            "sensitivity": sensitivity,
            "training_source": self.source_by_time[hours],
            "fallback": self.fallback_by_time[hours],
            "predicted_delta_bow": float(np.dot(sensitivity, recommended-x)),
        }

    def schedule(self, recipe: np.ndarray, origin: str) -> bool:
        if self.pending is not None:
            raise ValueError("이전 변경 레시피가 아직 적용되지 않았습니다.")
        if self.next_idx < 1:
            raise ValueError("먼저 Run 1회를 실행하여 Bow를 확인하세요.")
        measured = self.next_idx - 1
        apply_run = measured + self.cfg.delay
        if apply_run >= self.cfg.run_count:
            raise ValueError("예약한 Run이 시뮬레이션 범위를 벗어납니다.")
        candidate = np.asarray(recipe, dtype=float)
        if candidate.shape != (11,) or not np.all(np.isfinite(candidate)):
            raise ValueError("레시피는 숫자 온도 11개로 입력하세요.")
        change = np.clip(candidate - self.x_active, -self.cfg.max_change, self.cfg.max_change)
        candidate = np.clip(self.x_active + change,
                            self.x0 - self.cfg.max_total, self.x0 + self.cfg.max_total)
        if np.allclose(candidate, self.x_active, rtol=0, atol=1e-10):
            return False
        application_hours = float(self.run_hours[apply_run])
        sens = self.sensitivity_by_time[application_hours]
        self.pending = {
            "recipe": candidate,
            "apply_run": apply_run,
            "process_hours": application_hours,
            "source": origin,
            "predicted_delta": float(np.dot(sens, candidate - self.x_active)),
        }
        self.reserved_count += 1
        self.history[-1]["decision"] = origin
        self.history[-1]["reason"] = f"Run {apply_run} ({application_hours:g}Hr) 적용 예약"
        self.history[-1]["apply_to"] = apply_run
        return True

    def next_run(self) -> dict | None:
        if self.next_idx >= self.cfg.run_count:
            return None
        i = self.next_idx
        hours = float(self.run_hours[i])
        applied = False
        if self.pending is not None and i == self.pending["apply_run"]:
            self.x_active = self.pending["recipe"].copy()
            self.pending = None
            applied = True
            self.applied_count += 1

        self.cumulative_hours += hours
        disturbance = self.cfg.drift * i + self.noise[i]
        y_tuned = (self.y0 + self._slope(hours) * float(np.sum(self.x_active - self.x0))
                   + self._mode_offset(hours) + disturbance)
        y_keep = self.y0 + self._mode_offset(hours) + disturbance
        err = float(y_tuned - self.cfg.target)
        within = bool(self.cfg.lower <= y_tuned <= self.cfg.upper)

        row = {
            "run": i,
            "process_time": f"{hours:g}Hr",
            "process_hours": hours,
            "cumulative_hours": float(self.cumulative_hours),
            "bow_tuned": float(y_tuned),
            "bow_keep": float(y_keep),
            "error": err,
            "in_spec": within,
            "decision": "KEEP",
            "reason": "1.0~1.5 범위 이내" if within else "",
            "applied": applied,
            "apply_to": np.nan,
            "mean_temp": float(np.mean(self.x_active)),
            "sum_temp_change": float(np.sum(self.x_active - self.x0)),
        }
        self.history.append(row)
        self.next_idx += 1

        if self.pending is not None:
            row["decision"] = "WAIT"
            row["reason"] = f"Run {self.pending['apply_run']} 적용 대기"
        elif within:
            row["decision"] = "KEEP"
            row["reason"] = "품질 1.0~1.5 범위 이내"
        elif not self.cfg.auto:
            row["decision"] = "REVIEW"
            row["reason"] = "수동 모드: 엔지니어 결정 대기"
        else:
            where = "상한 초과" if y_tuned > self.cfg.upper else "하한 미달"
            apply_run = i + self.cfg.delay
            if apply_run >= self.cfg.run_count:
                row["decision"] = "END"
                row["reason"] = f"{where} / 다음 적용 Run이 시뮬레이션 범위 밖"
            else:
                proposed = self.propose(y_tuned, apply_run)
                if self.schedule(proposed, "TUNE"):
                    row["reason"] = f"{where} / Run {apply_run} ({self.run_hours[apply_run]:g}Hr) 예약"
                else:
                    row["decision"] = "LIMIT"
                    row["reason"] = f"{where} / 누적 온도 변경 한도 도달 또는 변경량 0"
        return row

    def run_all(self) -> None:
        while self.next_idx < self.cfg.run_count:
            self.next_run()

    def history_frame(self) -> pd.DataFrame:
        return pd.DataFrame(self.history)

    def metrics(self) -> str:
        if not self.history:
            return "아직 실행된 Run이 없습니다."
        df = self.history_frame()
        e_tuned = abs(df["bow_tuned"] - self.cfg.target)
        e_keep = abs(df["bow_keep"] - self.cfg.target)
        ok_tuned = df["bow_tuned"].between(self.cfg.lower, self.cfg.upper).mean()
        ok_keep = df["bow_keep"].between(self.cfg.lower, self.cfg.upper).mean()
        counts = Counter(df["decision"])
        return (f"MAE 추천 {e_tuned.mean():.3f} / 유지 {e_keep.mean():.3f} | "
                f"Spec 만족률 추천 {ok_tuned:.1%} / 유지 {ok_keep:.1%} | "
                f"예약 {self.reserved_count}회 / 적용 {self.applied_count}회 | "
                f"TUNE {counts['TUNE']} · KEEP {counts['KEEP']} · "
                f"WAIT {counts['WAIT']} · LIMIT {counts['LIMIT']} · "
                f"REVIEW {counts['REVIEW']}")


