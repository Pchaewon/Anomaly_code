"""Bow recipe tuning simulator v3: EQP_ID-based Tkinter GUI + Ridge / delayed Robbins-Monro.

Install: pip install numpy pandas scikit-learn matplotlib
Run:     python bow_recipe_tkinter_simulator_v3_eqp.py

The Bow outcomes are generated by a *synthetic* plant with user-set sensitivities.
Loading historical CSV trains direction weights; it does not validate plant dynamics.
CSV required: EQP_ID, 11 frame in temp 0pct..100pct, avg bow bf total, process_time.
Rows must be in old-to-new run order (within each EQP_ID).
Each equipment is trained independently; sparse time modes fall back to equipment-only pooled data.
process_time examples: 13.3Hr, 18.5Hr (numeric values also accepted).
"""

